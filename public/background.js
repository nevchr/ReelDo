import { INITIAL, mergeReels, validateBackup, classify, normalizeReel, organizeWorkspace } from './core.js';
const KEY = 'reeldo-v1';
let queue = Promise.resolve();
chrome.runtime.onInstalled.addListener(() => { chrome.storage.local.setAccessLevel({ accessLevel: 'TRUSTED_CONTEXTS' }); });
chrome.runtime.onMessage.addListener((message, sender, reply) => {
  const trusted = sender.id === chrome.runtime.id && sender.url?.startsWith(chrome.runtime.getURL(''));
  const capture = sender.id === chrome.runtime.id && /^https:\/\/(?:(?:www\.)?instagram\.com|(?:www\.|m\.)?tiktok\.com)\//.test(sender.tab?.url || '');
  if (!trusted && !capture) return;
  if (!['SAVE_STATE','CAPTURE_BATCH','SCAN_PROGRESS','GET_KNOWN','CAPTURE_VISIBLE'].includes(message.type)) return;
  if (message.type==='CAPTURE_VISIBLE') {
    if (!capture) return;
    (async()=>{
      const [active]=await chrome.tabs.query({active:true,windowId:sender.tab.windowId});
      if (active?.id!==sender.tab.id) return {error:'Keep the scanned tab selected while collecting thumbnails.'};
      const data=await chrome.tabs.captureVisibleTab(sender.tab.windowId,{format:'jpeg',quality:85});
      const [after]=await chrome.tabs.query({active:true,windowId:sender.tab.windowId});
      return after?.id===sender.tab.id ? {data} : {error:'The scanned tab lost focus; no thumbnail was saved.'};
    })().then(reply,error=>reply({error:error.message}));
    return true;
  }
  if (message.type === 'SAVE_STATE' && !trusted) return;
  const operation = queue.then(async () => {
    const state = (await chrome.storage.local.get(KEY))[KEY] || structuredClone(INITIAL);
    if (message.type === 'GET_KNOWN') return { ids: state.reels.filter(r => !message.refreshThumbnails && (!message.autoSort || r.status!=='inbox') && r.caption && (r.captureVersion>=2 || r.captionSource==='manual') && (message.platform==='tiktok' ? r.platform==='tiktok' : r.thumbnailData && r.mediaCaptureVersion>=2)).map(r=>r.id) };
    if (message.type === 'CAPTURE_BATCH') {
      if (!Array.isArray(message.reels) || message.reels.length > 200) throw new Error('Invalid scan batch.');
      state.reels = mergeReels(state.reels, message.reels);
      if (message.autoSort===true) {
        const ids=new Set(message.reels.map(r=>normalizeReel(r).id));
        state.reels=state.reels.map(r=>{if(!ids.has(r.id)||r.status!=='inbox')return r;const analysis=classify(r,state.settings?.strictness);return {...r,status:analysis.status,analysis};});
        const organized=organizeWorkspace(state);state.reels=organized.reels;state.tasks=organized.tasks;state.listVersion=organized.listVersion;
      }
    }
    if (message.type === 'SCAN_PROGRESS') state.scan = { running: Boolean(message.scan?.running), count: Number(message.scan?.count) || 0, message: String(message.scan?.message || '').slice(0,300), updatedAt: Date.now() };
    if (message.type === 'SAVE_STATE') {
      const next = validateBackup(message.state);
      // Capture updates are merged with edits so opening the dashboard cannot overwrite an active scan.
      next.reels = state.scan?.running ? mergeReels(next.reels, state.reels.filter(r => { const n = next.reels.find(n => n.id === r.id); return !n || (!n.caption && r.caption) || (!n.transcript && r.transcript) || (r.thumbnail && r.thumbnail!==n.thumbnail) || (r.thumbnailData && r.thumbnailData!==n.thumbnailData) || (r.mediaCaptureVersion>(n.mediaCaptureVersion||0)); })) : next.reels;
      if (state.scan?.running) {
        next.reels=next.reels.map(r=>{const captured=state.reels.find(old=>old.id===r.id);return r.status==='inbox'&&captured?.analysis&&r.caption===captured.caption&&r.transcript===captured.transcript ? {...r,status:captured.status,analysis:captured.analysis} : r;});
        for(const task of state.tasks) if(task.autoGenerated&&!next.tasks.some(t=>t.reelId===task.reelId)&&next.reels.some(r=>r.id===task.reelId&&r.status==='useful'&&!r.listDismissed))next.tasks.push(task);
        const organized=organizeWorkspace(next);next.reels=organized.reels;next.tasks=organized.tasks;next.listVersion=organized.listVersion;
      }
      next.scan = state.scan;
      await chrome.storage.local.set({ [KEY]: next });
    } else await chrome.storage.local.set({ [KEY]: state });
    return { ok: true };
  });
  queue = operation.catch(() => {});
  operation.then(reply, error => reply({ error: error.message }));
  return true;
});
